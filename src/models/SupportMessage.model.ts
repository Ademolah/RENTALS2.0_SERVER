import mongoose, { Schema } from 'mongoose';
import {
  AuthenticatedActor,
  IChatAttachment,
  ISupportMessage,
  ISupportMessageDocument,
  ISupportMessageModel,
  SanitizedMessageDTO,
} from '../types';

const attachmentSchema: Schema<IChatAttachment> = new Schema<IChatAttachment>(
  {
    url: { type: String, required: true, trim: true },
    publicId: { type: String, required: true, trim: true },
    mimeType: { type: String, required: true, trim: true },
    fileName: { type: String, trim: true },
    sizeBytes: { type: Number, min: 0 },
  },
  { _id: false }
);

const supportMessageSchema: Schema<ISupportMessage, ISupportMessageModel> = new Schema<
  ISupportMessage,
  ISupportMessageModel
>(
  {
    ticketId: {
      type: Schema.Types.ObjectId,
      ref: 'SupportTicket',
      required: true,
      index: true,
    },
    // Generated by Web/Mobile client (UUIDv4) to prevent duplicate messages on network retry
    clientMessageId: {
      type: String,
      required: true,
      trim: true,
      maxlength: 64,
    },
    senderId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      default: null,
    },
    senderRole: {
      type: String,
      enum: ['USER', 'LANDLORD', 'ADMIN', 'SYSTEM'],
      required: true,
    },
    senderDisplayName: {
      type: String,
      required: true,
      trim: true,
      maxlength: 80,
    },
    visibility: {
      type: String,
      enum: ['PUBLIC', 'INTERNAL_NOTE'],
      default: 'PUBLIC',
      index: true,
    },
    body: {
      type: String,
      default: '',
      trim: true,
      maxlength: 4000,
    },
    attachments: {
      type: [attachmentSchema],
      default: [],
      validate: {
        validator: (arr: IChatAttachment[]) => arr.length <= 5,
        message: 'Maximum of 5 attachments allowed per message.',
      },
    },
    readAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
    versionKey: false,
  }
);

supportMessageSchema.index({ ticketId: 1, clientMessageId: 1 }, { unique: true });
supportMessageSchema.index({ ticketId: 1, visibility: 1, _id: -1 });

supportMessageSchema.statics.toSafeDTO = function (
  message: ISupportMessageDocument,
  actor: AuthenticatedActor
): SanitizedMessageDTO | null {
  const isStaff = actor.role === 'ADMIN';

  // Hard security guard: NEVER serialize internal agent notes to Users or Landlords
  if (message.visibility === 'INTERNAL_NOTE' && !isStaff) {
    return null;
  }

  return {
    id: message._id.toString(),
    ticketId: message.ticketId.toString(),
    clientMessageId: message.clientMessageId,
    senderId:
      isStaff && message.senderId
        ? message.senderId.toString()
        : message.senderRole === 'ADMIN'
          ? null // Mask raw admin User ObjectId from external users
          : message.senderId
            ? message.senderId.toString()
            : null,
    senderRole: message.senderRole,
    senderDisplayName: message.senderDisplayName,
    visibility: message.visibility,
    body: message.body,
    attachments: message.attachments,
    readAt: message.readAt ? message.readAt.toISOString() : null,
    createdAt: message.createdAt.toISOString(),
  };
};

export const SupportMessage = mongoose.model<ISupportMessage, ISupportMessageModel>(
  'SupportMessage',
  supportMessageSchema
);